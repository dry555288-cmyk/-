def need(ok, msg):
    if not ok: raise RuntimeError(msg)

def sha(b): return hashlib.sha256(b).hexdigest()

def safe(path):
    for p in [path]+list(path.parents):
        need(not p.is_symlink(), 'SYMLINK_REFUSED:'+str(p))

def install(path, raw):
    safe(path)
    if os.path.lexists(path):
        need(path.is_file() and path.read_bytes()==raw,'EXISTING_DIFFERENT_RELEASE:'+str(path))
        print('REUSE_VERIFIED='+str(path),flush=True)
        return
    with path.open('xb') as f:
        f.write(raw); f.flush(); os.fsync(f.fileno())
    need(path.read_bytes()==raw,'INSTALL_READBACK')
    print('INSTALLED_CREATE_ONLY='+str(path),flush=True)

def unpack_install(self_path, data):
    encoded=self_path.read_bytes().split(b'\n__MINESIM_DUAL32_SCALE8_PAYLOAD__\n',1)
    need(len(encoded)==2,'PAYLOAD_MARKER_MISSING')
    raw=base64.b64decode(b''.join(encoded[1].split()),validate=True)
    need(sha(raw)==EXPECTED_PAYLOAD_SHA,'PAYLOAD_SHA_MISMATCH')
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        names=z.namelist();need(len(names)==len(set(names))<=20,'PAYLOAD_MEMBER_COUNT')
        need(sum(i.file_size for i in z.infolist())<8*1024**2,'PAYLOAD_EXPANSION_LIMIT')
        mf=json.loads(z.read('MANIFEST.json'));need(set(names)==set(mf)|{'MANIFEST.json'},'PAYLOAD_MANIFEST_SET')
        for n,rec in mf.items():
            need('/' not in n and '\\' not in n and n not in ('.','..'),'UNSAFE_PAYLOAD_NAME')
            b=z.read(n);need({'size':len(b),'sha256':sha(b)}==rec,'PAYLOAD_MEMBER_HASH:'+n)
        runner=z.read('runner.py')
    install(data/ARCHIVE,raw)
    install(data/RUNNER,runner)
    return data/RUNNER

class Mirror:
    """Log and terminal output in this same process; no tee/bash child process."""
    def __init__(self, stream, log): self.stream,self.log=stream,log
    def write(self,s):
        self.log.write(s);self.log.flush()
        try:self.stream.write(s);self.stream.flush()
        except (BrokenPipeError,OSError):pass
        return len(s)
    def flush(self):
        self.log.flush()
        try:self.stream.flush()
        except (BrokenPipeError,OSError):pass
    def isatty(self):return False

